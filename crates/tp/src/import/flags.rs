//! The distro flags of `inventories/group_vars/all` as Rust functions over
//! `Os`. The Jinja that defines them is not parsed: the bodies are the ones
//! the hand ports use (tp_basic `src/roles/*.rs`), keyed by flag name.

pub struct Flag {
    pub name: &'static str,
    /// Doc line for the emitted fn.
    pub doc: &'static str,
    pub body: &'static str,
    /// No image in `docker_images` reaches this flag; the design doc drops
    /// the branch. Emitted anyway with a TODO.
    pub unreachable: bool,
}

pub const FLAGS: &[Flag] = &[
    Flag {
        name: "redhat_based",
        doc: "Amazon is not in the list.",
        body: "os.family == Family::RedHat
        && match &os.distro {
            Distro::Fedora | Distro::Rocky | Distro::Alma => true,
            Distro::Other(id) => id == \"centos\" || id == \"rhel\",
            _ => false,
        }",
        unreachable: false,
    },
    Flag {
        name: "arch_based",
        doc: "Tests the family (omarchy is Arch).",
        body: "os.family == Family::Arch",
        unreachable: false,
    },
    Flag {
        name: "debian_based",
        doc: "Tests the distribution, not the family.",
        body: "matches!(os.distro, Distro::Debian | Distro::Ubuntu | Distro::PopOs)",
        unreachable: false,
    },
    Flag {
        name: "debian10_based",
        doc: "Debian 10.",
        body: "os.distro == Distro::Debian && os.version.major() == Some(10)",
        unreachable: true,
    },
    Flag {
        name: "ubuntu_based",
        doc: "Ubuntu and Pop!_OS.",
        body: "matches!(os.distro, Distro::Ubuntu | Distro::PopOs)",
        unreachable: false,
    },
    Flag {
        name: "amazonlinux2_based",
        doc: "Amazon Linux 2.",
        body: "os.distro == Distro::Amazon && os.version.major() == Some(2)",
        unreachable: true,
    },
    Flag {
        name: "amazonlinux2023_based",
        doc: "Amazon Linux 2023.",
        body: "os.distro == Distro::Amazon && os.version.major() == Some(2023)",
        unreachable: false,
    },
    Flag {
        name: "ubuntu2004_based",
        doc: "Ubuntu or Pop!_OS 20.04.",
        body: "ubuntu_based(os) && os.version.as_str() == \"20.04\"",
        unreachable: true,
    },
    Flag {
        name: "ubuntu2204_based",
        doc: "Ubuntu or Pop!_OS 22.04.",
        body: "ubuntu_based(os) && os.version.as_str() == \"22.04\"",
        unreachable: true,
    },
    Flag {
        name: "ubuntu2404_based",
        doc: "Ubuntu or Pop!_OS 24.04.",
        body: "ubuntu_based(os) && os.version.as_str() == \"24.04\"",
        unreachable: false,
    },
];

pub fn find(name: &str) -> Option<&'static Flag> {
    FLAGS.iter().find(|f| f.name == name)
}

/// `flags.rs` of the emitted crate. `lines` maps a flag name to its line in
/// `group_vars/all` when that file was found.
pub fn render(lines: &dyn Fn(&str) -> Option<usize>) -> String {
    let mut o = String::from(
        "//! Distro flags of `inventories/group_vars/all`, generated by `tp import`.\n\n\
         use telepatch::facts::os::{Distro, Family, Os};\n",
    );
    for f in FLAGS {
        o.push('\n');
        match lines(f.name) {
            Some(l) => o.push_str(&format!(
                "/// `inventories/group_vars/all:{l}`. {}\n",
                f.doc
            )),
            None => o.push_str(&format!("/// `{}`. {}\n", f.name, f.doc)),
        }
        o.push_str(&format!(
            "pub fn {}(os: &Os) -> bool {{\n    {}\n}}\n",
            f.name, f.body
        ));
    }
    o
}
