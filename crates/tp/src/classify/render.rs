//! Markdown rendering of a [`Report`]: a self-contained `## Current method`
//! section, no timestamps, no absolute paths.

use std::fmt::Write;

use super::{Report, TaskRef};

fn task_line(t: &TaskRef) -> String {
    let mut s = format!("- `{}:{}`", t.file, t.line);
    if let Some(n) = &t.name {
        let n = n.replace('\n', " ");
        let _ = write!(s, " {n}");
    }
    let _ = write!(s, " ({}", t.module);
    if let Some(p) = &t.primitive {
        let _ = write!(s, " -> {p}");
    }
    s.push(')');
    if let Some(v) = &t.via {
        let _ = write!(s, ", included from `{v}`");
    }
    s
}

/// The `## Task intent` skeleton. Task, Method and Signals are filled;
/// Intent, Shape, Adequate and Primitive are empty for the agent.
pub fn intent_skeleton(r: &Report, command: &str) -> String {
    let mut o = String::new();
    let _ = writeln!(o, "## Task intent\n");
    let _ = writeln!(
        o,
        "_Skeleton generated by `{command}`: Task, Method and Signals are the tool's. \
Fill Intent, Shape, Adequate and Primitive by hand, in this order, then the two lists below; \
the checker rejects an empty cell and a bare list label._\n"
    );
    let _ = writeln!(
        o,
        "| Task | Intent | Shape | Method | Signals | Adequate | Primitive |"
    );
    let _ = writeln!(o, "|---|---|---|---|---|---|---|");
    for row in &r.intent_rows {
        let name = row
            .name
            .as_deref()
            .map(|n| n.replace('\n', " ").replace('|', "\\|"))
            .unwrap_or_default();
        let signals = if row.signals.is_empty() {
            String::new()
        } else {
            row.signals.join("; ").replace('|', "\\|")
        };
        let _ = writeln!(
            o,
            "| `{}:{}` {} |  |  | {} | {} |  |  |",
            row.file, row.line, name, row.method, signals
        );
    }
    let _ = writeln!(o);
    let _ = writeln!(o, "Primitive gaps: \n");
    let _ = writeln!(o, "Built-primitive defects: ");
    if !r.skipped.is_empty() {
        let _ = writeln!(
            o,
            "\nSkipped by the loader (no row; decide each by hand):\n"
        );
        for s in &r.skipped {
            let _ = writeln!(o, "- `{}:{}` {}: {}", s.file, s.line, s.kind, s.detail);
        }
    }
    o
}

pub fn markdown(r: &Report) -> String {
    let mut o = String::new();
    let _ = writeln!(o, "## Current method\n");
    let _ = writeln!(o, "_Generated by `{}`._\n", r.command);
    let _ = writeln!(
        o,
        "{} tasks in scope; {} match no pattern and are plain module calls. \
A task is listed under every pattern it matches, so pattern counts overlap and do not sum to the task total.\n",
        r.total_tasks, r.plain_tasks
    );

    let _ = writeln!(o, "### By pattern\n");
    let _ = writeln!(o, "| Pattern | Tasks | Proposed telepatch primitive |");
    let _ = writeln!(o, "|---|---|---|");
    for p in &r.patterns {
        let _ = writeln!(o, "| {} | {} | {} |", p.title, p.count, p.primitive);
    }
    let _ = writeln!(o);
    for p in r.patterns.iter().filter(|p| p.count > 0) {
        let _ = writeln!(o, "#### {} ({} tasks)\n", p.title, p.count);
        let _ = writeln!(o, "Becomes: {}\n", p.primitive);
        for t in &p.tasks {
            let _ = writeln!(o, "{}", task_line(t));
        }
        let _ = writeln!(o);
    }

    let _ = writeln!(o, "### By module category\n");
    let _ = writeln!(
        o,
        "| Category | Tasks | Modules | Proposed telepatch primitive |"
    );
    let _ = writeln!(o, "|---|---|---|---|");
    for c in &r.categories {
        let modules: Vec<String> = c.modules.iter().map(|(m, n)| format!("{m} {n}")).collect();
        let prims = if c.primitives.is_empty() {
            "-".to_string()
        } else {
            c.primitives.join(", ")
        };
        let _ = writeln!(
            o,
            "| {} | {} | {} | {} |",
            c.category,
            c.count,
            modules.join(", "),
            prims
        );
    }
    let _ = writeln!(o);

    let _ = writeln!(o, "### Unclassified\n");
    if r.unclassified.is_empty() {
        let _ = writeln!(o, "None.\n");
    } else {
        let _ = writeln!(
            o,
            "No pattern matched and the module has no telepatch mapping:\n"
        );
        for t in &r.unclassified {
            let _ = writeln!(o, "{}", task_line(t));
        }
        let _ = writeln!(o);
    }

    let _ = writeln!(o, "### Skipped: out of scope\n");
    if r.skipped.is_empty() {
        let _ = writeln!(o, "None.");
    } else {
        for s in &r.skipped {
            let _ = writeln!(o, "- `{}:{}` {}: {}", s.file, s.line, s.kind, s.detail);
        }
    }
    o
}
