/// The skeleton for the real `dev_common` role from the corpus, through a
/// one-line playbook written beside the corpus roles.
#[test]
fn skel_corpus_dev_common() {
    let corpus = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("tests/corpus");
    let dir = tempfile::tempdir().unwrap();
    let playbook = dir.path().join("dev_base.yml");
    std::fs::write(
        &playbook,
        "- name: dev base\n  hosts: all\n  roles:\n    - dev_common\n",
    )
    .unwrap();
    let report = classify_playbook(&Options {
        playbook,
        roles_path: Some(corpus.join("roles")),
        base: Some(corpus),
        skip_roles: Vec::new(),
    })
    .unwrap();
    let skeleton = report.to_intent_skeleton("tp classify dev_base.yml --intent-skeleton");
    // The provenance line carries the temp dir; drop it for the snapshot.
    let body: String = skeleton
        .lines()
        .filter(|l| !l.starts_with("_Skeleton generated by"))
        .collect::<Vec<_>>()
        .join("\n");
    insta::assert_snapshot!(body);
}

